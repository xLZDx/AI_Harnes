"""Switch the live Claude Code hooks to the built Harness v2 set (out/claude), with a snapshot and a restore script.

  python tools/build.py --python <interpreter>                      # builds out/claude
  python tools/install_claude.py --home ~/.claude --snapshot <new folder>

What it does (nothing is deleted; every replaced file is copied to the snapshot first):
  settings.json "hooks"   -> replaced by the "hooks" of out/claude/settings.hooks.json. Every other key of
                             settings.json (permissions, env, model ...) is kept as it is.
  hooks/*.py, *.json      -> the built hook files are copied over the files of the same name in <home>/hooks.
                             Hook files that the new set does not use are left in place (just not called).
Before touching anything it checks: the snapshot folder does not exist, out/claude is complete, settings.json is
valid JSON with a "hooks" object (or has none), and every hook command in the new set points at a file that will exist
in <home>/hooks after the copy. restore.ps1 puts settings.json and the replaced hook files back.
The settings file is written atomically (temp file + replace). Hooks of the OLD set that are not in the new set
(for example the retired af_cli, rosetta and report hooks) are listed in the output.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import stat
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HOOK_FILE_RE = re.compile(r"[\w.-]+\.py\b")


_FAIL_AFTER = None  # test seam: raise OSError after the n-th write step (set from HARNESS_INSTALL_FAIL_AFTER in install())
_STEPS = 0


def _tick() -> None:
    """Count one write step (a copied hook file, then the written temp settings file); fail on the n-th if the seam is set."""
    global _STEPS
    _STEPS += 1
    if _FAIL_AFTER is not None and _STEPS == _FAIL_AFTER:
        raise OSError(f"simulated failure after write step {_STEPS} (HARNESS_INSTALL_FAIL_AFTER)")


def _ps(s: object) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def _commands(hooks: dict) -> list[str]:
    out = []
    for groups in hooks.values():
        for g in groups:
            for h in g.get("hooks", []):
                out.append(" ".join([str(h.get("command", "")), *map(str, h.get("args", []))]))
    return out


def _check_hooks(obj: object, what: str) -> dict:
    if not isinstance(obj, dict):
        raise ValueError(f"{what}: top level is not an object")
    hooks = obj.get("hooks", {})
    if not isinstance(hooks, dict):
        raise ValueError(f"{what}: 'hooks' is not an object")
    for ev, groups in hooks.items():
        if not isinstance(groups, list) or not all(
                isinstance(g, dict) and isinstance(g.get("hooks", []), list)
                and all(isinstance(h, dict) for h in g.get("hooks", [])) for g in groups):
            raise ValueError(f"{what}: hooks.{ev} must be a list of groups with a list of hook objects")
    return obj


def restore_script(home: Path, snap: Path, files: list[str]) -> str:
    lines = ["# Restores settings.json and the replaced hook files from this snapshot. Generated by tools/install_claude.py.",
             "# Hook files the install added (not in the snapshot) are moved aside as <name>.replaced-by-restore-<time>.",
             "$ErrorActionPreference = 'Stop'", f"$home_ = {_ps(home)}", f"$snap = {_ps(snap)}",
             "$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'",
             "$cur = Join-Path $home_ 'settings.json'; $old = Join-Path $snap 'settings.json'",
             "if (Test-Path -LiteralPath $old) { Copy-Item -LiteralPath $old -Destination $cur -Force }"]
    for name in files:
        lines += [f"$f = {_ps(name)}",
                  "$cur = Join-Path (Join-Path $home_ 'hooks') $f; $old = Join-Path (Join-Path $snap 'hooks') $f",
                  "if (Test-Path -LiteralPath $old) { Copy-Item -LiteralPath $old -Destination $cur -Force }",
                  "elseif (Test-Path -LiteralPath $cur) { Move-Item -LiteralPath $cur -Destination \"$cur.replaced-by-restore-$stamp\" }"]
    lines.append("Write-Output 'restored'")
    return "\n".join(lines) + "\n"


def install(home: Path, snap: Path, source: Path) -> int:
    new_path = source / "settings.hooks.json"
    src_hooks = source / "hooks"
    if not new_path.is_file() or not src_hooks.is_dir() or not any(src_hooks.glob("*.py")):
        print("install stopped, build output incomplete (run tools/build.py first)")
        return 1
    if snap.exists():
        print(f"install stopped: snapshot folder {snap} already exists; use a new one")
        return 1
    settings_path = home / "settings.json"
    try:  # everything that can fail on content fails before the first write
        new_cfg = _check_hooks(json.loads(new_path.read_text(encoding="utf-8-sig")), "built settings.hooks.json")
        if not new_cfg.get("hooks"):
            raise ValueError("built settings.hooks.json has no hooks")
        settings = json.loads(settings_path.read_text(encoding="utf-8-sig")) if settings_path.is_file() else {}
        _check_hooks(settings, "existing settings.json")
        files = sorted(p.name for p in src_hooks.iterdir() if p.is_file() and p.suffix in (".py", ".json"))
        missing = []
        for cmd in _commands(new_cfg["hooks"]):
            for name in HOOK_FILE_RE.findall(cmd):
                if name not in files and not (home / "hooks" / name).is_file():
                    missing.append(name)
        if missing:
            raise ValueError("the new set calls hook files that are not in the build: " + ", ".join(sorted(set(missing))))
    except (ValueError, OSError) as e:
        print(f"install stopped before any change: {e}")
        return 1
    old_cmds = _commands(settings.get("hooks") or {})
    try:
        snap.mkdir(parents=True)
        (snap / "restore.ps1").write_text(restore_script(home, snap, files), encoding="utf-8-sig", newline="\n")
        if settings_path.is_file():
            shutil.copy2(settings_path, snap / "settings.json")
        (snap / "hooks").mkdir()
        for name in files:
            p = home / "hooks" / name
            if p.is_file():
                shutil.copy2(p, snap / "hooks" / name)
    except OSError as e:
        shutil.rmtree(snap, ignore_errors=True)
        print(f"install stopped, the snapshot could not be written ({e}); nothing was changed")
        return 1
    global _FAIL_AFTER, _STEPS
    _STEPS = 0
    env_n = os.environ.get("HARNESS_INSTALL_FAIL_AFTER", "").strip()
    if env_n.isdigit():
        _FAIL_AFTER = int(env_n)
    tmp = home / "settings.json.tmp"
    try:
        (home / "hooks").mkdir(exist_ok=True)
        for name in files:
            dst = home / "hooks" / name
            if dst.exists():
                os.chmod(dst, stat.S_IWRITE)
            shutil.copy2(src_hooks / name, dst)
            _tick()
        merged = {**settings, "hooks": new_cfg["hooks"]}
        if "statusLine" not in settings and "agents_statusline.py" in files:  # S7-T6: never overwrite the operator's own
            py = Path(sys.executable).as_posix()
            merged["statusLine"] = {"type": "command", "command": f'"{py}" -s -X utf8 "{(home / "hooks" / "agents_statusline.py").as_posix()}"'}
        tmp.write_text(json.dumps(merged, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
        _tick()
        for attempt in range(8):  # Windows may refuse the replace for a moment (antivirus, indexer)
            try:
                os.replace(tmp, settings_path)
                break
            except PermissionError:
                if attempt == 7:
                    raise
                time.sleep(0.2)
    except BaseException as e:
        try:
            tmp.unlink()
        except OSError:
            pass
        print(f"install FAILED half-way ({type(e).__name__}: {e})\n  run {snap / 'restore.ps1'} to go back")
        return 1
    retired = sorted({n for c in old_cmds for n in HOOK_FILE_RE.findall(c)} -
                     {n for c in _commands(new_cfg['hooks']) for n in HOOK_FILE_RE.findall(c)})
    n_new = sum(len(g["hooks"]) for v in new_cfg["hooks"].values() for g in v)
    print(f"installed into {home}: settings.json hooks replaced ({len(old_cmds)} old entries -> {n_new} new), "
          f"{len(files)} hook files copied.")
    print(f"snapshot and restore script: {snap}")
    if retired:
        print("no longer called (files left in place): " + ", ".join(retired))
    print("NEXT: start a new Claude session; hooks changed in settings.json apply to new sessions.")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--home", type=Path, default=Path.home() / ".claude")
    ap.add_argument("--snapshot", type=Path, required=True)
    ap.add_argument("--source", type=Path, default=ROOT / "out" / "claude")
    a = ap.parse_args(argv)
    return install(a.home.resolve(), a.snapshot.resolve(), a.source.resolve())


if __name__ == "__main__":
    sys.exit(main())
